"""
Математические функции нижнего уровня, которые нужны при генерации M‑образов.

Сейчас модуль решает одну, но важную задачу:
  * по четырём точкам в 4D‑пространстве (x, y, z, u = F(x,y,z)) вычислить нормаль
    к гиперплоскости, проходящей через эти точки.

Результат — пять коэффициентов n1..n5, которые мы затем нормируем и записываем
как компоненты «расширенной» нормали в наши M‑образы.
Формулы полностью повторяют вывод из методички, включая исправление опечатки для n5.
"""

import math


# ============================================================================
# ВЫЧИСЛЕНИЕ НОРМАЛЕЙ n1..n5 ЧЕРЕЗ ОПРЕДЕЛИТЕЛИ
# ============================================================================

def compute_n12345(x1, y1, z1, u1, x2, y2, z2, u2, x3, y3, z3, u3, x4, y4, z4, u4):
    """
    Вычисляет компоненты нормали N = (n1, n2, n3, n4, n5) к касательной гиперплоскости
    в 4D-пространстве (x, y, z, u) по четырём точкам.
    
    Формулы из методички (вычисление через определители).
    
    Args:
        x1, y1, z1, u1: Координаты первой точки
        x2, y2, z2, u2: Координаты второй точки
        x3, y3, z3, u3: Координаты третьей точки
        x4, y4, z4, u4: Координаты четвёртой точки
    
    Returns:
        (n1, n2, n3, n4, n5) - компоненты нормали (не нормализованные)
    """
    # --- n1 ---
    B11 = z2*(u3 - u4) - u2*(z3 - z4) + (z3*u4 - z4*u3)
    B21 = y2*(u3 - u4) - u2*(y3 - y4) + (y3*u4 - y4*u3)
    B31 = y2*(z3 - z4) - z2*(y3 - y4) + (y3*z4 - y4*z3)
    B41 = y2*(z3*u4 - z4*u3) - z2*(y3*u4 - y4*u3) + u2*(y3*z4 - y4*z3)
    n1 = y1*B11 - z1*B21 + u1*B31 - B41

    # --- n2 ---
    C11 = z2*(u3 - u4) - u2*(z3 - z4) + (z3*u4 - z4*u3)
    C21 = x2*(u3 - u4) - u2*(x3 - x4) + (x3*u4 - x4*u3)
    C31 = x2*(z3 - z4) - z2*(x3 - x4) + (x3*z4 - x4*z3)
    C41 = x2*(z3*u4 - z4*u3) - z2*(x3*u4 - x4*u3) + u2*(x3*z4 - x4*z3)
    n2 = x1*C11 - z1*C21 + u1*C31 - C41

    # --- n3 ---
    D11 = y2*(u3 - u4) - u2*(y3 - y4) + (y3*u4 - y4*u3)
    D21 = x2*(u3 - u4) - u2*(x3 - x4) + (x3*u4 - x4*u3)
    D31 = x2*(y3 - y4) - y2*(x3 - x4) + (x3*y4 - x4*y3)
    D41 = x2*(y3*u4 - y4*u3) - y2*(x3*u4 - x4*u3) + u2*(x3*y4 - x4*y3)
    n3 = x1*D11 - y1*D21 + u1*D31 - D41

    # --- n4 ---
    E11 = y2*(z3 - z4) - z2*(y3 - y4) + (y3*z4 - y4*z3)
    E21 = x2*(z3 - z4) - z2*(x3 - x4) + (x3*z4 - x4*z3)
    E31 = x2*(y3 - y4) - y2*(x3 - x4) + (x3*y4 - x4*y3)
    E41 = x2*(y3*z4 - y4*z3) - y2*(x3*z4 - x4*z3) + z2*(x3*y4 - x4*y3)
    n4 = x1*E11 - y1*E21 + z1*E31 - E41

    # --- n5 ---
    F11 = y2*(z3*u4 - z4*u3) - z2*(y3*u4 - y4*u3) + u2*(y3*z4 - y4*z3)
    F21 = x2*(z3*u4 - z4*u3) - z2*(x3*u4 - x4*u3) + u2*(x3*z4 - x4*z3)
    F31 = x2*(y3*u4 - y4*u3) - y2*(x3*u4 - x4*u3) + u2*(x3*y4 - x4*y3)
    # F41 — по структуре аналогичен E41 (в методичке есть опечатка)
    F41 = x2*(y3*z4 - y4*z3) - y2*(x3*z4 - x4*z3) + z2*(x3*y4 - x4*y3)
    n5 = x1*F11 - y1*F21 + z1*F31 - u1*F41

    return n1, n2, n3, n4, n5


def normalize_n12345(n1, n2, n3, n4, n5):
    """
    Нормализует вектор нормали (n1, n2, n3, n4, n5) к единичной длине.
    
    Args:
        n1, n2, n3, n4, n5: Компоненты нормали
    
    Returns:
        (n1_norm, n2_norm, n3_norm, n4_norm, n5_norm) - нормализованные компоненты
        или None, если длина равна нулю
    """
    length = math.sqrt(n1*n1 + n2*n2 + n3*n3 + n4*n4 + n5*n5)
    if length == 0.0:
        return None
    
    return (n1/length, n2/length, n3/length, n4/length, n5/length)

