"""
Общие константы и маленькие утилиты, которые нужны практически всем частям проекта.

Здесь собраны:
  * договорённости по числовому диапазону значений в M‑образах;
  * функции перевода «число → RGB» и обратно (как для основного объёма, так и для заголовка);
  * функции преобразования между компонентами нормали n_i и целочисленным значением,
    которое мы реально сохраняем в BMP.

Идея модуля — чтобы все модули (генератор, визуализатор, парсер заголовка) говорили
на одном и том же «языке» и не дублировали побитовые формулы.
"""

# ============================================================================
# КОНСТАНТЫ ФОРМАТА M-ОБРАЗОВ
# ============================================================================

P_MAX = 256**3 - 1  # Максимальное значение 24‑битного цвета: числа от 0 до 16 777 215.

# Заголовок мы кодируем теми же 24‑битными цветами, но заранее сдвигаем значения,
# чтобы их нельзя было спутать с обычными данными нормалей (диапазон «далеко в сторону»).
HEADER_SHIFT = 1 << 23  # Сдвиг для параметров заголовка: 2^23.


# ============================================================================
# ФУНКЦИИ ДЛЯ РАБОТЫ С ЦВЕТОМ
# ============================================================================

def encode_color_to_rgb(value: int) -> tuple[int, int, int]:
    """
    Кодирует целое число в RGB-компоненты для записи в BMP.
    
    Args:
        value: Целое число (0..P_MAX для M-образов, или значение + HEADER_SHIFT для заголовка)
    
    Returns:
        (r, g, b) - кортеж из трёх компонент (0..255)
    """
    r = value & 0xFF
    g = (value >> 8) & 0xFF
    b = (value >> 16) & 0xFF
    return (r, g, b)


def decode_rgb_to_color(r: int, g: int, b: int) -> int:
    """
    Декодирует RGB-компоненты обратно в целое число.
    
    Args:
        r, g, b: Компоненты цвета (0..255)
    
    Returns:
        Целое число (для заголовка нужно вычесть HEADER_SHIFT)
    """
    return r + (g << 8) + (b << 16)


# ============================================================================
# ФУНКЦИИ ДЛЯ РАБОТЫ С ЗАГОЛОВКОМ
# ============================================================================

def encode_header_param(param_value) -> tuple[int, int, int]:
    """
    Кодирует параметр заголовка в RGB для записи в строку y=0.
    
    Args:
        param_value: Значение параметра (int или float)
    
    Returns:
        (r, g, b) - RGB компоненты
    """
    color = int(param_value) + HEADER_SHIFT
    return encode_color_to_rgb(color)


def decode_header_param(r: int, g: int, b: int):
    """
    Декодирует параметр заголовка из RGB.
    
    Args:
        r, g, b: RGB компоненты из пикселя
    
    Returns:
        Значение параметра (int)
    """
    color = decode_rgb_to_color(r, g, b)
    return color - HEADER_SHIFT


# ============================================================================
# ФУНКЦИИ ДЛЯ РАБОТЫ С M-ОБРАЗАМИ
# ============================================================================

def normal_to_mimage_value(normal_component: float) -> int:
    """
    Преобразует компоненту нормали в значение для M-образа.
    
    Args:
        normal_component: Компонента нормали n_i (должна быть в диапазоне [-1, 1])
    
    Returns:
        Значение для записи в M-образ (0..P_MAX)
    """
    return int(P_MAX * (1.0 + normal_component) / 2.0)


def mimage_value_to_normal(mimage_value: int) -> float:
    """
    Преобразует значение из M-образа обратно в компоненту нормали.
    
    Args:
        mimage_value: Значение из M-образа (0..P_MAX)
    
    Returns:
        Компонента нормали в диапазоне [-1, 1]
    """
    return 2.0 * mimage_value / P_MAX - 1.0

